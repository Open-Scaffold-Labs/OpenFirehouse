export function getFlowClass(gpm) {
  if (!gpm || gpm < 250) return FLOW_CLASSES.find(c => c.id === 'U');
  if (gpm >= 1500) return FLOW_CLASSES.find(c => c.id === 'AA');
  if (gpm >= 1000) return FLOW_CLASSES.find(c => c.id === 'A');
  if (gpm >= 500)  return FLOW_CLASSES.find(c => c.id === 'B');
  return FLOW_CLASSES.find(c => c.id === 'C');
}

